-- Lab assignments: a classroom's admins list Codeforces and LeetCode problems, and CPIntel
-- reads each student's accepted submissions on those sites to see which were solved.
--
-- Credit depends on the handle being the student's own, so a linked handle now has to be
-- proven before it earns anything: verified_at is set once the student has shown control of
-- it (a compilation error sent to a named Codeforces problem, or a code placed in their
-- LeetCode profile). Handles linked before this stay linked, unverified.

-- LeetCode comes back, as a handle only: nothing is synced from it beyond what a lab checks.
ALTER TABLE platform_accounts DROP CONSTRAINT chk_platform;
ALTER TABLE platform_accounts ADD  CONSTRAINT chk_platform
    CHECK (platform IN ('CODEFORCES', 'LEETCODE'));

ALTER TABLE platform_accounts ADD COLUMN verified_at      TIMESTAMPTZ;
ALTER TABLE platform_accounts ADD COLUMN verify_code      VARCHAR(40);
ALTER TABLE platform_accounts ADD COLUMN verify_issued_at TIMESTAMPTZ;

CREATE TABLE lab_assignments (
    lab_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id         BIGINT        NOT NULL,
    title                VARCHAR(200)  NOT NULL,
    description          VARCHAR(4000),
    opens_at             TIMESTAMPTZ   NOT NULL,
    due_at               TIMESTAMPTZ   NOT NULL,
    -- Off: only solves between opening and the deadline (or late, after it) count.
    -- On: a problem accepted at any time before the deadline counts.
    count_earlier_solves BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by           BIGINT,
    last_checked_at      TIMESTAMPTZ,
    created_at           TIMESTAMPTZ   DEFAULT now() NOT NULL,
    updated_at           TIMESTAMPTZ,
    CONSTRAINT fk_lab_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms(classroom_id) ON DELETE CASCADE,
    CONSTRAINT fk_lab_creator   FOREIGN KEY (created_by)   REFERENCES users(user_id)          ON DELETE SET NULL,
    CONSTRAINT chk_lab_window   CHECK (due_at > opens_at)
);
CREATE INDEX idx_lab_classroom ON lab_assignments(classroom_id);
CREATE INDEX idx_lab_window    ON lab_assignments(opens_at, due_at);

CREATE TABLE lab_problems (
    lab_problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id         BIGINT        NOT NULL,
    platform       VARCHAR(20)   NOT NULL,
    -- "1700/A" on Codeforces (contest or gym id, then the index); the title slug on LeetCode.
    problem_key    VARCHAR(120)  NOT NULL,
    title          VARCHAR(300)  NOT NULL,
    url            VARCHAR(500)  NOT NULL,
    -- A Codeforces rating, or Easy/Medium/Hard on LeetCode.
    difficulty     VARCHAR(20),
    marks          NUMERIC(10,2) NOT NULL DEFAULT 1,
    ordering       INTEGER       NOT NULL,
    CONSTRAINT fk_lp_lab       FOREIGN KEY (lab_id) REFERENCES lab_assignments(lab_id) ON DELETE CASCADE,
    CONSTRAINT uq_lp_problem   UNIQUE (lab_id, platform, problem_key),
    CONSTRAINT chk_lp_platform CHECK (platform IN ('CODEFORCES', 'LEETCODE')),
    CONSTRAINT chk_lp_marks    CHECK (marks >= 0)
);

-- The groups a lab is set for. None means the whole classroom.
CREATE TABLE lab_groups (
    lab_id   BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    PRIMARY KEY (lab_id, group_id),
    CONSTRAINT fk_lg_lab   FOREIGN KEY (lab_id)   REFERENCES lab_assignments(lab_id) ON DELETE CASCADE,
    CONSTRAINT fk_lg_group FOREIGN KEY (group_id) REFERENCES contest_groups(group_id) ON DELETE CASCADE
);

-- The first qualifying accepted submission a student made to a lab problem.
CREATE TABLE lab_solves (
    solve_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_problem_id BIGINT       NOT NULL,
    user_id        BIGINT       NOT NULL,
    solved_at      TIMESTAMPTZ  NOT NULL,
    -- After the deadline: shown, but worth no marks.
    late           BOOLEAN      NOT NULL,
    handle         VARCHAR(100) NOT NULL,
    submission_ref VARCHAR(100),
    recorded_at    TIMESTAMPTZ  DEFAULT now() NOT NULL,
    CONSTRAINT fk_ls_problem FOREIGN KEY (lab_problem_id) REFERENCES lab_problems(lab_problem_id) ON DELETE CASCADE,
    CONSTRAINT fk_ls_user    FOREIGN KEY (user_id)        REFERENCES users(user_id)               ON DELETE CASCADE,
    CONSTRAINT uq_ls_solve   UNIQUE (lab_problem_id, user_id)
);
CREATE INDEX idx_ls_user ON lab_solves(user_id);
