-- Teaching assistants, and the marks they give.
--
-- A judge gives a verdict, not a mark: a problem is worth its full marks once accepted and
-- nothing otherwise. Teaching assistants read what each student submitted and set the marks
-- themselves — part marks for a nearly right answer, or none for one that passed by luck.
--
-- A TA is an ordinary account linked to a classroom, like an admin added as staff. The same
-- person can be a student in one classroom and a TA in another, so this is a link and not a
-- role. Admins create the account if it does not exist yet, and link the one that does.

CREATE TABLE classroom_tas (
    classroom_id  BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    added_by      BIGINT,
    added_at      TIMESTAMPTZ  DEFAULT now() NOT NULL,
    PRIMARY KEY (classroom_id, user_id),
    CONSTRAINT fk_ct_classroom FOREIGN KEY (classroom_id) REFERENCES classrooms(classroom_id) ON DELETE CASCADE,
    CONSTRAINT fk_ct_user      FOREIGN KEY (user_id)      REFERENCES users(user_id)           ON DELETE CASCADE,
    CONSTRAINT fk_ct_added_by  FOREIGN KEY (added_by)     REFERENCES users(user_id)           ON DELETE SET NULL
);

CREATE INDEX idx_ct_user ON classroom_tas (user_id);

-- What one TA marks on one examination. Each row is a question, a range of students, or both
-- (that question for those students); a null field means all of them. A TA's rows add up, so
-- two rows give the union of the two.
--
-- A range is a span of usernames, both ends included, compared in natural order so that roll
-- numbers sort as numbers (cs2 before cs10).
CREATE TABLE exam_ta_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id    BIGINT       NOT NULL,
    ta_user_id    BIGINT       NOT NULL,
    problem_label VARCHAR(16),
    range_from    VARCHAR(50),
    range_to      VARCHAR(50),
    created_by    BIGINT,
    created_at    TIMESTAMPTZ  DEFAULT now() NOT NULL,
    CONSTRAINT fk_eta_contest    FOREIGN KEY (contest_id) REFERENCES group_contests(contest_id) ON DELETE CASCADE,
    CONSTRAINT fk_eta_ta         FOREIGN KEY (ta_user_id) REFERENCES users(user_id)             ON DELETE CASCADE,
    CONSTRAINT fk_eta_created_by FOREIGN KEY (created_by) REFERENCES users(user_id)             ON DELETE SET NULL
);

CREATE INDEX idx_eta_contest ON exam_ta_assignments (contest_id);
CREATE INDEX idx_eta_ta      ON exam_ta_assignments (ta_user_id);

-- A mark set by hand for one student on one question. It replaces the judge's all-or-nothing
-- mark on the leaderboard and in the export. No row means the judge's mark stands.
CREATE TABLE exam_marks (
    mark_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id    BIGINT        NOT NULL,
    user_id       BIGINT        NOT NULL,
    problem_label VARCHAR(16)   NOT NULL,
    marks         NUMERIC(10,2) NOT NULL,
    remark        VARCHAR(1000),
    -- The archived submission that was on screen when the mark was given.
    submission_id VARCHAR(64),
    marked_by     BIGINT,
    marked_at     TIMESTAMPTZ   DEFAULT now() NOT NULL,
    CONSTRAINT fk_em_contest   FOREIGN KEY (contest_id) REFERENCES group_contests(contest_id) ON DELETE CASCADE,
    CONSTRAINT fk_em_user      FOREIGN KEY (user_id)    REFERENCES users(user_id)             ON DELETE CASCADE,
    CONSTRAINT fk_em_marked_by FOREIGN KEY (marked_by)  REFERENCES users(user_id)             ON DELETE SET NULL,
    CONSTRAINT uq_em_cell UNIQUE (contest_id, user_id, problem_label),
    CONSTRAINT chk_em_marks CHECK (marks >= 0)
);
