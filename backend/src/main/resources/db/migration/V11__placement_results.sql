-- The placement gauntlet's results.
--
-- The roadmap reads mastery from solve history, so a strong newcomer used to land on the very
-- first node. The gauntlet places them instead, and this keeps each attempt: what they scored
-- in each area and how many roadmap skills that marked as done. Kept per attempt rather than
-- overwritten, so a retake later in the term shows progress instead of replacing the record.

CREATE TABLE placement_results (
    result_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    -- A rating-scale estimate across all six areas.
    overall_rating  INTEGER     NOT NULL,
    -- Per-area results as JSON: [{ "section": "graphs", "tiersPassed": 2, "rating": 1600 }, …]
    sections        TEXT        NOT NULL,
    nodes_placed    INTEGER     NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_placement_user_created ON placement_results (user_id, created_at DESC);
