-- Publishing an examination's questions from the question bank to the classroom's judge, and
-- telling candidates when something changes.
--
-- An admin picks checked questions from the classroom's bank for an examination and publishes:
-- CPIntel creates the DOMjudge contest the examination already names, uploads each question as
-- a problem package, labels them A, B, C… in the chosen order, and fills in the examination's
-- problem list. Publishing again before the start brings the judge in line with the choice.
-- After the start a single question can be published again to fix it, with a notice to
-- candidates and the existing rejudge.

-- The questions chosen for an examination, in order, and what of each is on the judge.
CREATE TABLE exam_bank_questions (
    contest_id         BIGINT        NOT NULL,
    question_id        BIGINT        NOT NULL,
    ordinal            INTEGER       NOT NULL,
    -- Set once uploaded: the judge's problem id, and the question version it holds.
    judge_problem_id   VARCHAR(100),
    label              VARCHAR(16),
    published_version  INTEGER,
    published_at       TIMESTAMPTZ,
    published_by       BIGINT,
    PRIMARY KEY (contest_id, question_id),
    CONSTRAINT fk_ebq_contest  FOREIGN KEY (contest_id)   REFERENCES group_contests(contest_id) ON DELETE CASCADE,
    -- A question in an examination is archived, never deleted.
    CONSTRAINT fk_ebq_question FOREIGN KEY (question_id)  REFERENCES bank_questions(question_id) ON DELETE RESTRICT,
    CONSTRAINT fk_ebq_by       FOREIGN KEY (published_by) REFERENCES users(user_id)             ON DELETE SET NULL,
    CONSTRAINT uq_ebq_ordinal  UNIQUE (contest_id, ordinal) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX idx_ebq_question ON exam_bank_questions (question_id);

-- The examination's contest on the judge, when CPIntel created it.
CREATE TABLE exam_publications (
    contest_id        BIGINT         PRIMARY KEY,
    judge_contest_id  VARCHAR(100)   NOT NULL,
    -- True once CPIntel created that contest. Only such a contest is ever published into.
    contest_created   BOOLEAN        DEFAULT FALSE NOT NULL,
    status            VARCHAR(16)    NOT NULL,
    judge_start       TIMESTAMPTZ,
    judge_end         TIMESTAMPTZ,
    published_by      BIGINT,
    published_at      TIMESTAMPTZ,
    note              VARCHAR(2000),
    CONSTRAINT fk_ep_contest FOREIGN KEY (contest_id)   REFERENCES group_contests(contest_id) ON DELETE CASCADE,
    CONSTRAINT fk_ep_by      FOREIGN KEY (published_by) REFERENCES users(user_id)             ON DELETE SET NULL,
    CONSTRAINT ck_ep_status  CHECK (status IN ('PUBLISHED', 'FAILED'))
);

-- Messages to everyone sitting an examination, shown in the arena once it has started.
CREATE TABLE exam_announcements (
    announcement_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id       BIGINT         NOT NULL,
    message          VARCHAR(1000)  NOT NULL,
    created_by       BIGINT,
    created_at       TIMESTAMPTZ    DEFAULT now() NOT NULL,
    CONSTRAINT fk_ea_contest FOREIGN KEY (contest_id) REFERENCES group_contests(contest_id) ON DELETE CASCADE,
    CONSTRAINT fk_ea_by      FOREIGN KEY (created_by) REFERENCES users(user_id)             ON DELETE SET NULL
);

CREATE INDEX idx_ea_contest ON exam_announcements (contest_id, created_at);
