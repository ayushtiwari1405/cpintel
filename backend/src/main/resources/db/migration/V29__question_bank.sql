-- A classroom's question bank: exam questions written in CPIntel instead of on the judge.
--
-- Until now an examination's statements and test data lived only on DOMjudge, put there by
-- someone signed in to its jury pages, and CPIntel read the problem list back. A question
-- written here is CPIntel's own: its admins and TAs edit it, and an admin later publishes it to
-- the classroom's judge as part of an examination. The judge then holds a copy, not the
-- original. Questions entered on DOMjudge directly still work as before.
--
-- Nothing in these tables reaches the judge by itself. A question is a draft until it has been
-- checked against its model solution, and only an admin's publish sends anything to DOMjudge.

CREATE TABLE bank_questions (
    question_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id     BIGINT        NOT NULL,
    title            VARCHAR(200)  NOT NULL,
    -- Markdown, with $…$ for maths. Rendered to the PDF the judge serves.
    statement        TEXT          DEFAULT '' NOT NULL,
    time_limit_ms    INTEGER       DEFAULT 1000 NOT NULL,
    memory_limit_mb  INTEGER       DEFAULT 256 NOT NULL,
    -- How output is compared with the answer, as DOMjudge's default validator does it:
    -- EXACT       tokens must match, case included; spacing and line breaks may differ
    -- IGNORE_CASE as EXACT, ignoring upper and lower case
    -- FLOAT       numbers may differ by float_tolerance (absolute or relative)
    checker          VARCHAR(16)   DEFAULT 'EXACT' NOT NULL,
    float_tolerance  DOUBLE PRECISION,
    model_language   VARCHAR(16),
    model_source     TEXT,
    -- DRAFT until the model solution has been run on every test and agrees with each answer.
    -- Any change sends it back to DRAFT.
    status           VARCHAR(16)   DEFAULT 'DRAFT' NOT NULL,
    -- Counts edits, so two people saving the same question cannot silently overwrite each other.
    version          INTEGER       DEFAULT 0 NOT NULL,
    archived         BOOLEAN       DEFAULT FALSE NOT NULL,
    created_by       BIGINT,
    updated_by       BIGINT,
    created_at       TIMESTAMPTZ   DEFAULT now() NOT NULL,
    updated_at       TIMESTAMPTZ   DEFAULT now() NOT NULL,
    CONSTRAINT fk_bq_classroom  FOREIGN KEY (classroom_id) REFERENCES classrooms(classroom_id) ON DELETE CASCADE,
    CONSTRAINT fk_bq_created_by FOREIGN KEY (created_by)   REFERENCES users(user_id)           ON DELETE SET NULL,
    CONSTRAINT fk_bq_updated_by FOREIGN KEY (updated_by)   REFERENCES users(user_id)           ON DELETE SET NULL,
    CONSTRAINT ck_bq_time       CHECK (time_limit_ms BETWEEN 100 AND 20000),
    CONSTRAINT ck_bq_memory     CHECK (memory_limit_mb BETWEEN 16 AND 2048),
    CONSTRAINT ck_bq_checker    CHECK (checker IN ('EXACT', 'IGNORE_CASE', 'FLOAT')),
    CONSTRAINT ck_bq_tolerance  CHECK (checker <> 'FLOAT' OR float_tolerance > 0),
    CONSTRAINT ck_bq_status     CHECK (status IN ('DRAFT', 'READY')),
    CONSTRAINT ck_bq_language   CHECK (model_language IS NULL OR model_language IN ('c', 'cpp', 'python3'))
);

CREATE INDEX idx_bq_classroom ON bank_questions (classroom_id, archived);

-- A question's tests, in order: samples (shown to candidates) and secret tests (judged only).
-- The bytes are kept apart in bank_question_test_data, so listing a question never reads them.
CREATE TABLE bank_question_tests (
    test_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id    BIGINT       NOT NULL,
    sample         BOOLEAN      NOT NULL,
    ordinal        INTEGER      NOT NULL,
    -- The name it was uploaded under, for the person reading the list; never used as a path.
    name           VARCHAR(120) NOT NULL,
    input_bytes    INTEGER      NOT NULL,
    -- Null while the answer is missing: it may later be generated from the model solution.
    answer_bytes   INTEGER,
    created_by     BIGINT,
    created_at     TIMESTAMPTZ  DEFAULT now() NOT NULL,
    CONSTRAINT fk_bqt_question   FOREIGN KEY (question_id) REFERENCES bank_questions(question_id) ON DELETE CASCADE,
    CONSTRAINT fk_bqt_created_by FOREIGN KEY (created_by)  REFERENCES users(user_id)              ON DELETE SET NULL,
    -- Deferred so a reorder can swap two positions inside one transaction.
    CONSTRAINT uq_bqt_position UNIQUE (question_id, sample, ordinal) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE bank_question_test_data (
    test_id  BIGINT  PRIMARY KEY,
    input    BYTEA   NOT NULL,
    answer   BYTEA,
    CONSTRAINT fk_bqtd_test FOREIGN KEY (test_id) REFERENCES bank_question_tests(test_id) ON DELETE CASCADE
);
