#!/usr/bin/env bash
# The production CPIntel stack, shaped like the exam server, for a load test on this machine.
#
#   ./scripts/loadtest/stack.sh up       # build and start it, monitoring and the judge included
#   ./scripts/loadtest/stack.sh status   # what is running, and memory in use
#   ./scripts/loadtest/stack.sh down     # stop it and delete its data (its own volumes only)
#
# Runs under its own compose project (cpintel-loadtest), so its volumes are not a development
# stack's. Secrets are generated once into out/loadtest.env and reused. See README.md here.
# LOADTEST_JUDGE=remote leaves the local DOMjudge out, for a judge on another machine.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
OUT="$HERE/out"
ENV_FILE="$OUT/loadtest.env"
PROJECT=cpintel-loadtest

LOCAL_JUDGE=true
[ "${LOADTEST_JUDGE:-local}" = remote ] && LOCAL_JUDGE=false

compose() {
  local profiles=(--profile monitoring)
  $LOCAL_JUDGE && profiles+=(--profile judge)
  docker compose -p "$PROJECT" --env-file "$ENV_FILE" \
    -f "$ROOT/docker-compose.yml" -f "$HERE/docker-compose.loadtest.yml" \
    "${profiles[@]}" "$@"
}

key() { head -c 48 /dev/urandom | base64 | tr -d '\n=' | tr '+/' '-_'; }

write_env() {
  mkdir -p "$OUT"
  umask 077
  # Added to a file written before the judge moved onto this machine, too.
  if [ -f "$ENV_FILE" ] && ! grep -q '^JUDGE_DB_PASSWORD=' "$ENV_FILE"; then
    printf 'JUDGE_DB_ROOT_PASSWORD=%s\nJUDGE_DB_PASSWORD=%s\n' "$(key)" "$(key)" >> "$ENV_FILE"
  fi
  [ -f "$ENV_FILE" ] && return
  cat > "$ENV_FILE" <<ENV
# Generated by stack.sh for the load test. Throwaway: delete it with the stack.
POSTGRES_USER=cpintel
POSTGRES_PASSWORD=$(key)
MONGO_USER=cpintel
MONGO_PASSWORD=$(key)
REDIS_PASSWORD=$(key)
JWT_SECRET=$(key)
CPINTEL_SESSION_KEY=$(key)
CPINTEL_DOMJUDGE_CREDENTIAL_KEY=$(key)
CPINTEL_EXAM_PASSWORD_KEY=$(key)
CPINTEL_RUNNER_TOKEN=$(key)
CPINTEL_ADMIN_EMAIL=loadtest-admin@cpintel.local
CPINTEL_ADMIN_USERNAME=loadtest_admin
CPINTEL_ADMIN_PASSWORD=$(key | cut -c1-24)
CPINTEL_DOMAIN=localhost
CPINTEL_PUBLIC_URL=https://localhost
GRAFANA_PASSWORD=$(key | cut -c1-16)
# The simulator reaches nginx from this machine, so every simulated candidate arrives from the
# Docker gateway: one address, exactly like a lab behind a NAT. Declared as one, as a real lab
# would be, so the sign-in limits are the ones a real room meets.
CPINTEL_LAB_NETWORKS=172.29.0.1/32
CPINTEL_DESKTOP_BUILD=0
JUDGE_DB_ROOT_PASSWORD=$(key)
JUDGE_DB_PASSWORD=$(key)
ENV
  echo "Wrote $ENV_FILE"
}

# The judgehosts sign in with the password the domserver generated on its first start, so they
# start once it is up and that password can be read from it.
start_judgehosts() {
  echo "Waiting for the domserver …"
  for _ in $(seq 1 75); do
    curl -sf http://127.0.0.1:12345/api/v4/info >/dev/null && break
    sleep 4
  done
  local secret
  secret="$(docker exec cpintel-lt-domserver cat /opt/domjudge/domserver/etc/restapi.secret \
    | awk '!/^#/ && NF >= 4 { print $4; exit }')"
  [ -n "$secret" ] || { echo "Could not read the judgehost password from the domserver" >&2; exit 1; }
  # A domserver recreated over an existing database (a cpuset change is enough) generates a new
  # password the database does not have, and says so in the file. The database is this stack's
  # own, so it is set to the file's rather than leaving the judgehosts locked out.
  if docker exec cpintel-lt-domserver grep -q '^# NOTE(password-mismatch)' \
      /opt/domjudge/domserver/etc/restapi.secret; then
    local hash root
    hash="$(docker exec cpintel-lt-domserver php -r 'echo password_hash($argv[1], PASSWORD_BCRYPT);' "$secret")"
    root="$(grep '^JUDGE_DB_ROOT_PASSWORD=' "$ENV_FILE" | cut -d= -f2)"
    printf "UPDATE user SET password='%s' WHERE username='judgehost';\n" "$hash" \
      | docker exec -i -e MYSQL_PWD="$root" cpintel-lt-judge-db mariadb -uroot domjudge
    docker exec cpintel-lt-domserver sed -i '/^# NOTE(password-mismatch)/d; /^# The database was not/d' \
      /opt/domjudge/domserver/etc/restapi.secret
    echo "Set the judge database's judgehost password to the domserver's."
  fi
  JUDGEDAEMON_PASSWORD="$secret" compose --profile judgehosts up -d judgehost-0 judgehost-1 judgehost-2
  echo "Judge: http://127.0.0.1:12345 (admin; password: docker exec cpintel-lt-domserver" \
       "cat /opt/domjudge/domserver/etc/initial_admin_password.secret)"
}

case "${1:-}" in
  up)
    write_env
    compose up -d --build
    $LOCAL_JUDGE && start_judgehosts
    echo "Waiting for https://localhost/actuator/health …"
    for _ in $(seq 1 90); do
      if curl -skf https://localhost/actuator/health >/dev/null; then
        echo "Up. Admin: $(grep ^CPINTEL_ADMIN_EMAIL "$ENV_FILE" | cut -d= -f2) (password in $ENV_FILE)"
        echo "Grafana http://127.0.0.1:3000 (admin / GRAFANA_PASSWORD), alerts http://127.0.0.1:9090/alerts"
        exit 0
      fi
      sleep 4
    done
    echo "Not healthy after 6 minutes; see: docker compose -p $PROJECT logs backend" >&2
    exit 1
    ;;
  status)
    compose ps
    docker stats --no-stream --format '{{.Name}}\t{{.CPUPerc}}\t{{.MemUsage}}' \
      | grep -E '^cpintel-' || true
    ;;
  down)
    compose --profile judge --profile judgehosts down -v
    echo "Stopped and removed the load-test stack and its volumes."
    ;;
  *)
    sed -n '2,10p' "$0"
    exit 1
    ;;
esac
