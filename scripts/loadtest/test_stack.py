#!/usr/bin/env python3
"""
Tests for stack.sh's settings file and its MongoDB start, without Docker.

    python3 -I scripts/loadtest/test_stack.py

stack.sh is sourced (which only defines its functions) with LOADTEST_OUT pointing at a temporary
directory, so out/loadtest.env is never read or written. start_mongo is run against a stand-in
`docker` and a stand-in account script that only record how they were called. Standard library
only.
"""
import os
import re
import stat
import subprocess
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
STACK = HERE / "stack.sh"


def _parse(text):
    """The KEY=value lines of a settings file, as (key, value) pairs in order."""
    return [tuple(line.split("=", 1)) for line in text.splitlines()
            if line and not line.startswith("#")]


class StackTest(unittest.TestCase):

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="cpintel-loadtest-test-")
        self.addCleanup(self._tmp.cleanup)
        self.tmp = Path(self._tmp.name)
        self.out = self.tmp / "out"
        self.env_file = self.out / "loadtest.env"

    def run_stack(self, snippet, extra_env=None):
        env = {k: v for k, v in os.environ.items() if not k.startswith(("MONGO_", "CPINTEL_"))}
        env["LOADTEST_OUT"] = str(self.out)
        env.update(extra_env or {})
        return subprocess.run(["bash", "-c", f'source "{STACK}"; {snippet}'],
                              capture_output=True, text=True, env=env)

    def write_env(self):
        result = self.run_stack("write_env")
        self.assertEqual(result.returncode, 0, result.stderr)
        return self.env_file.read_text()

    # -- the settings file ----------------------------------------------------------------------

    def test_a_new_file_has_the_app_account_and_no_duplicates(self):
        text = self.write_env()
        pairs = _parse(text)
        keys = [k for k, _ in pairs]
        self.assertEqual(len(keys), len(set(keys)), "a setting is defined twice")
        values = dict(pairs)
        self.assertEqual(values["MONGO_APP_USER"], "cpintel_app")
        self.assertRegex(values["MONGO_APP_PASSWORD"], r"^[A-Za-z0-9_-]{32,}$")
        self.assertNotEqual(values["MONGO_APP_PASSWORD"], values["MONGO_PASSWORD"])
        self.assertEqual(stat.S_IMODE(self.env_file.stat().st_mode), 0o600)

    def test_running_again_changes_nothing(self):
        first = self.write_env()
        self.assertEqual(self.write_env(), first)
        self.assertEqual(self.write_env(), first)

    def test_an_older_file_gains_the_account_once_and_keeps_its_secrets(self):
        self.out.mkdir()
        older = ("# Generated by stack.sh for the load test.\n"
                 "POSTGRES_USER=cpintel\nPOSTGRES_PASSWORD=pg-old\nMONGO_USER=cpintel\n"
                 "MONGO_PASSWORD=mongo-old\nJWT_SECRET=jwt-old\n")
        self.env_file.write_text(older)

        text = self.write_env()
        self.assertTrue(text.startswith(older), "an existing line was changed")
        values = dict(_parse(text))
        self.assertEqual(values["MONGO_APP_USER"], "cpintel_app")
        self.assertRegex(values["MONGO_APP_PASSWORD"], r"^[A-Za-z0-9_-]{32,}$")
        self.assertIn("JUDGE_DB_PASSWORD", values)
        keys = [k for k, _ in _parse(text)]
        self.assertEqual(len(keys), len(set(keys)), "a setting is defined twice")

        self.assertEqual(self.write_env(), text, "a second run rotated or appended something")

    def test_an_existing_app_password_is_never_rotated(self):
        self.out.mkdir()
        self.env_file.write_text("MONGO_USER=cpintel\nMONGO_PASSWORD=m\nJUDGE_DB_ROOT_PASSWORD=r\n"
                                 "JUDGE_DB_PASSWORD=j\nMONGO_APP_USER=cpintel_app\n"
                                 "MONGO_APP_PASSWORD=kept-as-it-was\n")
        before = self.env_file.read_text()
        self.assertEqual(self.write_env(), before)

    # -- start_mongo ----------------------------------------------------------------------------

    def stand_ins(self):
        """A `docker` and a scripts/mongo-app-user.sh that record their calls in calls.log."""
        log = self.tmp / "calls.log"
        bin_dir = self.tmp / "bin"
        bin_dir.mkdir()
        (bin_dir / "docker").write_text(f'#!/bin/sh\necho "docker $*" >> "{log}"\n')
        root = self.tmp / "root"
        (root / "scripts").mkdir(parents=True)
        (root / "scripts" / "mongo-app-user.sh").write_text(
            "#!/bin/sh\n"
            f'echo "account args=[$*] container=$CPINTEL_MONGO_CONTAINER user=$MONGO_APP_USER '
            f'password=$MONGO_APP_PASSWORD" >> "{log}"\n')
        for f in (bin_dir / "docker", root / "scripts" / "mongo-app-user.sh"):
            f.chmod(0o755)
        return log, {"PATH": f"{bin_dir}:{os.environ['PATH']}"}, root

    def test_start_mongo_starts_only_mongo_then_gives_it_the_account(self):
        self.write_env()
        password = dict(_parse(self.env_file.read_text()))["MONGO_APP_PASSWORD"]
        log, env, root = self.stand_ins()

        result = self.run_stack(f'ROOT="{root}"; start_mongo', env)
        self.assertEqual(result.returncode, 0, result.stderr)

        calls = log.read_text().splitlines()
        self.assertEqual(len(calls), 2, calls)
        self.assertTrue(calls[0].startswith("docker compose -p cpintel-loadtest "), calls[0])
        self.assertTrue(calls[0].endswith(" up -d mongodb"), calls[0])
        self.assertIn(f"--env-file {self.env_file}", calls[0])
        # The account script gets this stack's container and settings, and the password only
        # through its environment.
        self.assertEqual(calls[1], f"account args=[] container=cpintel-lt-mongo user=cpintel_app password={password}")

    def test_start_mongo_refuses_an_empty_password_before_starting_anything(self):
        self.out.mkdir()
        self.env_file.write_text("MONGO_APP_USER=cpintel_app\nMONGO_APP_PASSWORD=\n")
        log, env, root = self.stand_ins()

        result = self.run_stack(f'ROOT="{root}"; start_mongo', env)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("MONGO_APP_PASSWORD is empty", result.stdout + result.stderr)
        self.assertFalse(log.exists(), "something was started")

    def test_up_gives_mongo_its_account_before_starting_the_rest(self):
        text = STACK.read_text()
        up = re.search(r"\n  up\)\n(.*?);;", text, re.S).group(1)
        self.assertLess(up.index("write_env"), up.index("start_mongo"))
        self.assertLess(up.index("start_mongo"), up.index("compose up -d --build"))


if __name__ == "__main__":
    unittest.main(verbosity=2)
